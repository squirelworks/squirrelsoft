#!/usr/bin/env python3
"""Write sqqr test symbols using segno, an independent QR encoder.

Usage: python3 -I tools/gen_fixtures.py fixtures/symbols.txt   (from libs/sqqr)
       python3 -I tools/gen_fixtures.py --check-tables include/../src/sqqr.c

Fixture format, one symbol per group:
  S <version> <L|M|Q|H> <mask> <expected payload hex>
  <one line per module row, hex of the row's bits, MSB first, padded to a byte>
The C test decodes every grid and compares version, level, mask and payload.

--check-tables cross-checks the C error-correction block table and the
alignment position formula against segno's own tables.
"""
import random
import re
import sys

import segno
import segno.consts as sc

LEVELS = "LMQH"


def rows_hex(matrix):
    out = []
    for row in matrix:
        bits = "".join("1" if x else "0" for x in row)
        bits += "0" * (-len(bits) % 8)
        out.append("%0*x" % (len(bits) // 4, int(bits, 2)))
    return out


def symbol(lines, content, payload, **kw):
    q = segno.make(content, micro=False, boost_error=False, **kw)
    lines.append("S %d %s %d %s" % (q.version, q.error, q.mask, payload.hex()))
    lines.extend(rows_hex(q.matrix))


def main(path):
    lines = ["# sqqr fixtures, generated by tools/gen_fixtures.py with segno. Do not edit."]
    r = random.Random(20261104)
    cases = [
        ("HELLO WORLD", 1, "q", None),
        ("01234567", 1, "m", None),
        ("https://squirrel.works/", 2, "l", None),
        ("SquirrelQR test 123", None, "h", None),
    ]
    for text, version, err, mask in cases:
        symbol(lines, text, text.encode(), version=version, error=err, mask=mask)
    # Every mask on one version.
    for m in range(8):
        symbol(lines, "MASK TEST %d" % m, ("MASK TEST %d" % m).encode(), version=3, error="m", mask=m)
    # Version ranges, levels and modes, including version information (v7+).
    for v in (5, 7, 9, 10, 14, 20, 26, 27, 33, 40):
        lvl = LEVELS[v % 4]
        data_cw = sum(e.num_blocks * e.num_data for e in sc.ECC[v][sc.ERROR_MAPPING[lvl]])
        n = max(1, data_cw // 2)  # half full, so segno keeps this version
        data = bytes(r.randrange(0x20, 0x7F) for _ in range(n))
        symbol(lines, data, data, version=v, error=lvl.lower(), mode="byte")
        num = "".join(r.choice("0123456789") for _ in range(n))
        symbol(lines, num, num.encode(), version=v, error=lvl.lower(), mode="numeric")
    # Kanji (emitted as Shift JIS) and an ECI-tagged UTF-8 payload.
    kanji = "漢字テスト"
    symbol(lines, kanji, kanji.encode("shift_jis"), version=2, error="m", mode="kanji")
    utf = "Suica 残高 ¥2,480"
    symbol(lines, utf, utf.encode("utf-8"), version=3, error="l", eci=True, encoding="utf-8")
    open(path, "w").write("\n".join(lines) + "\n")


def check_tables(c_path):
    src = open(c_path).read()
    body = src[src.index("EC_BLOCKS[40][4][5] = {"):]
    rows = re.findall(r"\{\{(.*?)\}\},", body)[:40]
    bad = 0
    for v, row in enumerate(rows, 1):
        cells = [tuple(map(int, c.split(","))) for c in re.findall(r"\{?([\d, ]+)\}", row)]
        for lvl, cell in zip(LEVELS, cells):
            ecs = sc.ECC[v][sc.ERROR_MAPPING[lvl]]
            g = [(e.num_blocks, e.num_total, e.num_data) for e in ecs]
            want = (g[0][1] - g[0][2], g[0][0], g[0][2],
                    g[1][0] if len(g) > 1 else 0, g[1][2] if len(g) > 1 else 0)
            if cell != want:
                print("EC table mismatch v%d %s: %s != %s" % (v, lvl, cell, want))
                bad += 1
    if len(rows) != 40:
        print("expected 40 table rows, found", len(rows))
        bad += 1
    print("EC table: %s" % ("ok" if not bad else "%d mismatches" % bad))
    return bad


if __name__ == "__main__":
    if sys.argv[1] == "--check-tables":
        sys.exit(1 if check_tables(sys.argv[2]) else 0)
    main(sys.argv[1])
