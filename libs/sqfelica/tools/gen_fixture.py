#!/usr/bin/env python3
"""Write the sqfelica parity fixture from SquirrelSuica's Python parser.

The C test (tests/test_sqfelica.c) parses the same blocks and must produce the
same fields, so the C library and felica_parse.py cannot drift apart.

Usage: python3 -I tools/gen_fixture.py OUT   (run from libs/sqfelica)

Format, one record per line:
  G <brand>            start a history group (suica, nanaco, edy)
  B <32 hex>           one history block, newest first
  E kind date time fare balance terminal process enter exit
                       one expected entry; time/enter/exit are '-' when absent
  .                    end of group
  L <brand> <hex|-> [<hex|->] <balance|->   one balance check
"""
import importlib.util
import random
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PARSER = HERE.parent.parent.parent / "squirrelsuica" / "felica_parse.py"


def load_parser():
    spec = importlib.util.spec_from_file_location("felica_parse", PARSER)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["felica_parse"] = mod
    spec.loader.exec_module(mod)
    return mod


fp = load_parser()
TIME_RE = re.compile(r"· (\d{2}):(\d{2})(?: ·|$)")


def entry_line(e):
    m = TIME_RE.search(e.note)
    t = f"{m.group(1)}:{m.group(2)}" if m else "-"
    return "E {} {} {} {} {} {:02x} {:02x} {} {}".format(
        e.kind, e.date, t, e.fare_yen, e.balance_yen, e.terminal, e.process,
        e.enter_code or "-", e.exit_code or "-")


def group(out, brand, blocks):
    parse = {
        "suica": fp.parse_history_blocks,
        "nanaco": fp.parse_nanaco_history_blocks,
        "edy": fp.parse_edy_history_blocks,
    }[brand]
    out.append(f"G {brand}")
    out.extend(f"B {b.hex()}" for b in blocks)
    out.extend(entry_line(e) for e in parse(list(blocks)))
    out.append(".")


def nanaco_block(typ, amount, bal, y, m, d, hh, mm):
    return fp._hist_nanaco(typ, amount, bal, y, m, d, hh, mm)


def edy_block(typ, days, secs, amount, bal):
    out = bytearray(16)
    out[0] = typ
    out[4:8] = ((days << 17) | secs).to_bytes(4, "big")
    out[8:12] = amount.to_bytes(4, "big")
    out[12:16] = bal.to_bytes(4, "big")
    return bytes(out)


def suica_product(terminal, process, y, m, d, hh, mm, bal):
    b = bytearray(fp.hist_rail(terminal, process, y, m, d, 0, 0, 0, 0, bal))
    tw = (hh << 11) | (mm << 5)
    b[6], b[7] = (tw >> 8) & 0xFF, tw & 0xFF
    return bytes(b)


def rand_suica(r):
    terminal = r.choice([0x16, 0x16, 0x05, 0xC7, 0xC8, 0x08, r.randrange(256)])
    process = r.choice([0x01, 0x02, 0x03, 0x0D, 0x0F, 0x14, 0x15, 0x46, 0x48, 0x4A,
                        0x84, 0xC6, r.randrange(256)])
    b = bytearray(r.randbytes(16))
    b[0], b[1] = terminal, process
    if r.random() < 0.8:
        y, m, d = r.randrange(2000, 2100), r.randrange(1, 13), r.randrange(1, 32)
        dw = ((y - 2000) << 9) | (m << 5) | d
        b[4], b[5] = dw >> 8, dw & 0xFF
    if r.random() < 0.3:
        b[6] = b[7] = 0
    if r.random() < 0.3:
        b[8] = b[9] = 0
    return bytes(b)


def main():
    out = ["# sqfelica parity fixture, generated by tools/gen_fixture.py from",
           "# squirrelsuica/felica_parse.py. Do not edit by hand."]
    demo = [
        fp.hist_rail(0x16, 0x01, 2026, 10, 28, 0xE3, 0x59, 0xE3, 0x5E, 2480),
        fp.hist_rail(0x16, 0x01, 2026, 10, 27, 0x25, 0x07, 0x25, 0x0A, 2648),
        fp.hist_rail(0x16, 0x02, 2026, 10, 26, 0x01, 0x01, 0, 0, 2858),
        fp.hist_rail(0x16, 0x01, 2026, 10, 25, 0x25, 0x01, 0x25, 0x02, 858),
    ]
    group(out, "suica", demo)
    group(out, "suica", [
        fp.hist_rail(0x05, 0x0D, 2026, 1, 2, 0x12, 0x34, 0, 0, 1000),
        suica_product(0xC7, 0x46, 2026, 1, 2, 9, 41, 1220),
        suica_product(0xC8, 0x46, 2026, 1, 1, 25, 70, 1500),
        bytes(16),
        fp.hist_rail(0x16, 0x48, 2025, 12, 31, 0x90, 0x10, 0x90, 0x11, 1700, region=0xD0),
        fp.hist_rail(0x16, 0x99, 2025, 12, 30, 0x01, 0x02, 0x03, 0x04, 1600),
        # BCD date fallback (month 0 in the packed word).
        bytes([0x16, 0x01, 0, 0, 0x26, 0x10, 0x28, 0x00, 0x25, 0x02, 0x10, 0x00, 0, 0, 0, 0]),
    ])
    group(out, "nanaco", [
        nanaco_block(0x47, 480, 5200, 2026, 10, 28, 18, 42),
        nanaco_block(0x6F, 3000, 5680, 2026, 10, 27, 12, 5),
        nanaco_block(0x83, 100, 2680, 2026, 10, 26, 30, 5),
        nanaco_block(0x35, 0, 2680, 2026, 13, 26, 1, 2),
        nanaco_block(0x00, 1, 2, 2026, 1, 1, 1, 1),
        nanaco_block(0x47, 200000, 900000, 2026, 1, 1, 1, 1),
    ])
    group(out, "edy", [
        edy_block(0x20, 9800, 18 * 3600 + 42 * 60 + 7, 480, 5200),
        edy_block(0x02, 9799, 3600, 3000, 5680),
        edy_block(0x04, 59, 0, 1000, 2680),
        edy_block(0x77, 32767, 0x1FFFF, 5, 600000),
    ])

    r = random.Random(20261104)
    for _ in range(12):
        group(out, "suica", [rand_suica(r) for _ in range(r.randrange(1, 8))])
    for _ in range(4):
        group(out, "nanaco", [bytes([r.choice([0x47, 0x5C, 0x70, 0x83, r.randrange(256)])])
                              + r.randbytes(15) for _ in range(r.randrange(1, 5))])
        group(out, "edy", [bytes([r.choice([0x20, 0x02, 0x04, r.randrange(256)])])
                           + r.randbytes(15) for _ in range(r.randrange(1, 5))])

    def hx(b):
        return b.hex() if b is not None else "-"

    def opt(v):
        return "-" if v is None else str(v)

    suica_cases = [
        (fp.hist_rail(0x16, 1, 2026, 1, 1, 0, 0, 0, 0, 2480), None),
        (None, bytes(11) + bytes([0xB0, 0x09]) + bytes(3)),
        (fp.hist_rail(0x16, 1, 2026, 1, 1, 0, 0, 0, 0, 30000),
         bytes(11) + bytes([0xE8, 0x03]) + bytes(3)),
        (fp.hist_rail(0x16, 1, 2026, 1, 1, 0, 0, 0, 0, 60000), bytes(11) + bytes([0xE8, 0x03]) + bytes(3)),
        (fp.hist_rail(0x16, 1, 2026, 1, 1, 0, 0, 0, 0, 60000), bytes(11) + bytes([0x60, 0xEA]) + bytes(3)),
        (bytes(10), bytes(12)),
    ]
    for _ in range(8):
        suica_cases.append((r.randbytes(16), r.randbytes(16)))
    for a, b in suica_cases:
        out.append(f"L suica {hx(a)} {hx(b)} {opt(fp.suica_balance(a, b))}")
    for brand, fn in (("nanaco", fp.nanaco_balance), ("edy", fp.edy_balance),
                      ("waon", fp.waon_balance)):
        for b in (bytes([0x50, 0x14, 0, 0]) + bytes(12), bytes([0xff] * 16), r.randbytes(16)):
            out.append(f"L {brand} {b.hex()} {fn(b)}")

    Path(sys.argv[1]).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
